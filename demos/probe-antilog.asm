01040*  THE ANTILOG PROBE.  IT READS ARGUMENT CARDS, CALLS ANTLOG ON
01050*  EACH, AND PRINTS THE ARGUMENT, THE MANTISSA AND THE DECADE.
01060*  THAT IS ALL IT DOES.  IT IS SCAFFOLDING - ITS NUMBERS ARE
01070*  CHECKED AGAINST A FUNCTION AND NOT AGAINST A GOLDEN PAGE, SO
01080*  NO GOLDEN IS CUT FOR IT.
01090*
01100*  10K, ONE CHANNEL, A 1402 READ-PUNCH AND A 1403 MODEL 2, CHAIN A.
01110*
01120*  ANTLOG SOLVES 10 TO THE F AS ANTA OF F1 TIMES 1 PLUS R TIMES
01130*  C1 PLUS C2 TIMES R - HORNER, THREE MULTIPLIES.  ANTA IS 100
01140*  CONTIGUOUS TEN-POSITION DCW CARDS OF 10 TO THE I OVER 100, AND
01150*  THE FETCH TAKES THE TOP EIGHT.  THE LOW TWO ARE GUARD DIGITS
01160*  THE MLC DISCARDS, NOT FILLER.  ENTRY 99 IS 9.772372210 AND ITS
01170*  TOP EIGHT ARE 97723722 - IT IS NOT 99770006, WHICH IS 10 TO THE
01180*  0.999 AND BELONGS TO A TABLE THIS DESIGN DOES NOT HAVE.
01190*
01200*  DEC AND F1 ARE FIELD SLICES - MLN OFF THE BIASED ARGUMENT, NOT
01210*  ARITHMETIC.  R IS THE LOW FIVE DIGITS OF F, WHICH IS THE SAME
01220*  SLICE, AND IS WHY NO SUBTRACT FORMS IT.  ARGB AND KBIAS ARE
01230*  NINE POSITIONS - THE BIASED ARGUMENT NEEDS TWO INTEGER DIGITS,
01240*  AND EIGHT COULD NOT EVEN HOLD THE BIAS CONSTANT.
01250*
01260*  THE MACHINE HAS NO SHIFT.  A RESCALE IS ONE MLC FROM A CONSTANT
01270*  OFFSET.  A +5 HALF ADJUSTS ONE POSITION RIGHT OF THE TARGET
01280*  UNITS BEFORE EVERY TRUNCATING MOVE.  THE ARITHMETIC RUNS ON
01290*  MAGNITUDES SO THAT ALGEBRAIC ADD NEVER SEES A MINUS - MLZS
01300*  STAMPS THE SIGN, WHICH IS PI.JOB-S OWN IDIOM.
01310*
01320*  X1 IS LOADED BY MLCWA AND NEVER BY MLC.  AFTER THE LOADER RUNS,
01330*  00025 THROUGH 00029 HOLDS A WORD MARK, SO AN MLC STOPS AFTER
01340*  TWO CHARACTERS AND THE NEXT INDEXED REFERENCE TAKES AN ADDRESS
01350*  CHECK.  MLCWA MOVES FIVE CHARACTERS AND THEIR WORD MARKS.
01360*
01370*  SUBROUTINE RETURN IS SBR ANTX+5 THEN B 00000 - THE G CCCCC B
01380*  MECHANISM, 69.75 MICROSECONDS UNACCELERATED ON A BASE 1411.
01390*  G STORES FIVE CHARACTERS ENDING AT ITS C-ADDRESS AND A BRANCH
01400*  IS J AAAAA D, SEVEN CHARACTERS, SO THE ADDRESS UNITS IS ANTX+5.
01410*  THE B 00000 AT ANTX IS PATCHED AT RUN TIME AND IS NOT A BUG.
01420*  THE ACCELERATOR IS NOT ASSUMED ANYWHERE IN THIS DECK.
01430*
01440*  OP T, TABLE LOOKUP, IS IMPLEMENTED AND DELIBERATELY UNUSED.  A
01450*  100-ENTRY SEARCH IS 2,511 MICROSECONDS AGAINST 183 FOR THE
01460*  INDEXED MLC - THE GRID IS UNIFORM AND THE ARGUMENT DIGITS ARE
01470*  THE INDEX, SO A RIGHT-TO-LEFT SCAN BUYS NOTHING AND COSTS 135X.
